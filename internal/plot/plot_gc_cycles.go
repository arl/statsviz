package plot

import (
	"runtime/metrics"
	"time"
)

var _ = register(description{
	metrics: []string{
		"/gc/cycles/automatic:gc-cycles",
		"/gc/cycles/forced:gc-cycles",
	},
	getvalues: func() getvalues {
		deltaauto := delta[uint64]()
		deltaforced := delta[uint64]()

		return func(_ time.Time, samples []metrics.Sample) any {
			auto := samples[idx_gc_cycles_automatic_gc_cycles].Value.Uint64()
			forced := samples[idx_gc_cycles_forced_gc_cycles].Value.Uint64()

			return []uint64{
				deltaauto(auto),
				deltaforced(forced),
			}
		}
	},
	layout: Scatter{
		Name:   "gc-cycles",
		Tags:   []tag{tagGC},
		Title:  "Completed GC Cycles",
		Type:   "bar",
		Events: "lastgc",
		Layout: ScatterLayout{
			BarMode: "stack",
			Yaxis: ScatterYAxis{
				Title:   "gc-cycles",
				Integer: true,
			},
		},
		Subplots: []Subplot{
			{Name: "automatic", Unitfmt: "%{y}"},
			{Name: "forced", Unitfmt: "%{y}"},
		},
		InfoText: `<i>automatic</i> is the delta of <b>/gc/cycles/automatic:gc-cycles</b>. Count of completed GC cycles generated by the Go runtime.
<i>forced</i> is the delta of <b>/gc/cycles/forced:gc-cycles</b>. Count of completed GC cycles forced by the application.`,
	},
})
